/** 과목 이름 → 교과 계열 (편제표 과목명·프로그램 과목명 모두) */
export function subjectFamily(subject: string | null | undefined): SubjectFamily | null {
  const s = subject ?? "";
  if (/정보|인공지능|프로그래밍|데이터 과학|소프트웨어/.test(s)) return "정보";
  if (/영어|영미|English/i.test(s)) return "영어";
  if (/수학|대수|미적분|기하|확률|통계|경제 수학|인공지능 수학/.test(s)) return "수학";
  if (/과학|물리|화학|생명|지구|천문|융합과학/.test(s)) return "과학";
  if (/국어|문학|화법|독서|작문|언어|매체/.test(s)) return "국어";
  if (/사회|한국사|역사|세계사|동아시아|지리|윤리|정치|법|경제|도덕|사상|세계시민/.test(s)) return "사회";
  return null;
}

