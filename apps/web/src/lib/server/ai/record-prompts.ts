/** 시스템 프롬프트 (교과 세특은 교과 계열별 SKILL, 창체·행발은 공통 문체 + 영역 설명) */
function basePrompt(kind: RecordKind, subject?: string | null): string {
  if (kind === "세특") {
    const fam = subjectFamily(subject);
    const f = fam ? FAMILY[fam] : GENERIC;
    const label = fam ? `${fam} 교과` : `${subject ?? ""} 교과`.trim();
    return [
      TOP_RULES,
      `1) 목적: 교사가 준 근거 자료를 바탕으로 학교생활기록부 ${label} 세부능력 및 특기사항(교과세특) 기록을 완성함.${subject ? ` 과목은 ${subject}임.` : ""}`,
      `2) 역할과 톤: ${f.teacher} 관점에서 교사 시점의 평가 기록 문장으로 씀. 품격 있고 신뢰감 있는 문장을 간결하고 실무적으로 쓰며 맞춤법과 띄어쓰기를 정확히 함.`,
      `3) 드러낼 요소(가능한 범위에서 자연스럽게): ${f.elements}. 타 교과 연계가 가능하면 과도하지 않게 녹임.`,
      CONTENT_RULES,
      `4-3) 행동동사 참고: ${f.verbs}`,
      OUTPUT_RULES,
      PROCESS(f.expert, f.checks),
      `7) 예외 처리: 근거 자료가 빈약하면 세부 내용을 지어내지 말고 ${f.fallback} 수준으로 일반화하여 긍정적으로 기록함.`,
      f.examples.length ? `예시(문체 참고용, 내용을 베끼지 않음):\n${f.examples.map((e) => `- ${e}`).join("\n")}` : "",
    ].filter(Boolean).join("\n\n");
  }
  const n = NON_SUBJECT[kind];
  return [
    TOP_RULES,
    `1) 목적: 교사가 준 근거 자료를 바탕으로 학교생활기록부 ${n.area} 기록을 완성함.`,
    `2) 역할과 톤: ${n.teacher} 관점에서 교사 시점의 평가 기록 문장으로 씀. 품격 있고 간결하며 맞춤법과 띄어쓰기를 정확히 함.`,
    `3) 중심 내용: ${n.focus}.`,
    CONTENT_RULES,
    OUTPUT_RULES,
    PROCESS("학교생활기록부 기재요령에 밝은 교육 전문가", "- 기재 금지 사항(교외 수상, 공인 어학 성적, 기관이나 대학이나 회사 이름, 부모 직업)과 사실관계를 확인함."),
    `7) 예외 처리: 근거 자료가 빈약하면 지어내지 말고 ${n.fallback} 수준으로 일반화하여 긍정적으로 기록함.`,
  ].join("\n\n");
}

/** 프로그램 영역(DraftCategory) → 프롬프트 종류 */
export function kindOfArea(area: string): RecordKind {
  if (area.includes("자율")) return "자율·자치";
  if (area.includes("동아리")) return "동아리";
  if (area.includes("진로")) return "진로";
  return "세특";
}

/** 생기부 문장 시스템 프롬프트 = 속초고 세특 프롬프트 + 기재요령 금칙어 (lib/domain/forbidden.ts) */
export function recordSystemPrompt(kind: RecordKind, subject?: string | null): string {
  return `${basePrompt(kind, subject)}\n\n${FORBIDDEN_PROMPT}`;
}
