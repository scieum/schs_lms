export const TIP_CATEGORIES = ["구조", "문장", "서술어", "점검", "기재요령", "기타"] as const;
export type TipCategory = (typeof TIP_CATEGORIES)[number];
export const isTipCategory = (v: unknown): v is TipCategory => (TIP_CATEGORIES as readonly string[]).includes(String(v));

export type Tip = {
  id: string;
  category: TipCategory;
  title: string;
  body: string;
  source: string | null;
  /** 올린 교사 (처음 글은 null) */
  authorId: string | null;
  /** 화면에 보이는 이름 ("○○○ 선생님" · "생기부 팁 모음") */
  authorName: string;
  createdAt: string;
  updatedAt: string;
};

export const TIP_LIMITS = { title: 60, body: 3000, source: 200 } as const;

/** 올리기 전 검사. 문제 없으면 null */
export function checkTip(input: { category: string; title: string; body: string; source?: string | null }): string | null {
  if (!isTipCategory(input.category)) return "분류를 골라 주세요";
  const title = input.title.trim(), body = input.body.trim();
  if (title.length < 2) return "제목을 2자 이상 써 주세요";
  if (title.length > TIP_LIMITS.title) return `제목은 ${TIP_LIMITS.title}자까지예요`;
  if (body.length < 10) return "내용을 10자 이상 써 주세요";
  if (body.length > TIP_LIMITS.body) return `내용은 ${TIP_LIMITS.body.toLocaleString("ko-KR")}자까지예요`;
  if ((input.source ?? "").trim().length > TIP_LIMITS.source) return `출처는 ${TIP_LIMITS.source}자까지예요`;
  return null;
}

/** 찾기 · 분류 거르기 (최신 위) */
export function filterTips(tips: Tip[], q: { category?: string | null; text?: string | null }): Tip[] {
  const words = (q.text ?? "").trim().toLowerCase().split(/\s+/).filter(Boolean);
  return tips
    .filter((t) => !q.category || q.category === "전체" || t.category === q.category)
    .filter((t) => words.every((w) => `${t.title} ${t.body} ${t.source ?? ""}`.toLowerCase().includes(w)))
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt) || a.title.localeCompare(b.title, "ko"));
}

export const tipCounts = (tips: Tip[]): Record<string, number> =>
  Object.fromEntries([["전체", tips.length], ...TIP_CATEGORIES.map((c) => [c, tips.filter((t) => t.category === c).length])]);

