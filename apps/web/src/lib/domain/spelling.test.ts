import { describe, expect, it } from "vitest";
import { applySpell, placeAiFixes, spellCheck } from "./spelling";

const fix = (t: string) => applySpell(t, spellCheck(t));

describe("맞춤법 규칙 사전 (N38)", () => {
  it.each([
    ["실험이 잘 됬음.", "실험이 잘 됐음."],
    ["이렇게 하면 되요.", "이렇게 하면 돼요."],
    ["준비가 되서 발표함.", "준비가 돼서 발표함."],
    ["왜 안되는지 확인함.", "왜 안 되는지 확인함."],
    ["숙제를 안하고 놀았음.", "숙제를 안 하고 놀았음."],
    ["포기하지않고 끝까지 함.", "포기하지 않고 끝까지 함."],
    ["자료를 제시함으로서 설득함.", "자료를 제시함으로써 설득함."],
    ["그래프를 제시 함으로써 이해를 도움.", "그래프를 제시함으로써 이해를 도움."],
    ["끝까지 확인할수 있도록 정리함.", "끝까지 확인할 수 있도록 정리함."],
    ["발표할때 자료를 씀.", "발표할 때 자료를 씀."],
    ["모를때까지 묻는 끈기를 보임.", "모를 때까지 묻는 끈기를 보임."],
    ["코딩할줄 알게 됨.", "코딩할 줄 알게 됨."],
    ["문제를 해결하는데 있어 끈기를 보임.", "문제를 해결하는 데 있어 끈기를 보임."],
    ["몇일 동안 관찰함.", "며칠 동안 관찰함."],
    ["금새 익힘.", "금세 익힘."],
    ["모둠장 역활을 맡음.", "모둠장 역할을 맡음."],
    ["일일히 확인함.", "일일이 확인함."],
    ["제작년 대회에 나감.", "재작년 대회에 나감."],
    ["어의없는 실수를 바로잡음.", "어이없는 실수를 바로잡음."],
    ["왠만한 문제는 혼자 풂.", "웬만한 문제는 혼자 풂."],
    ["오랫만에 다시 실험함.", "오랜만에 다시 실험함."],
    ["설레임을 표현함.", "설렘을 표현함."],
    ["진로에 대한 바램을 밝힘.", "진로에 대한 바람을 밝힘."],
  ])("%s → %s", (from, to) => {
    expect(fix(from)).toBe(to);
  });

  it.each([
    "그때 실험 결과를 정리함.",
    "학생 수가 적어 표본이 부족함.",
    "할수록 실력이 늘어남.",
    "자신감이 생김. 반장으로서 책임을 다함.",
    "수업에 안정적으로 참여함.",
    "때때로 질문하며 끈기를 보임.",
    "바람의 세기를 측정함.",
    "지금 세 가지 방법을 비교함.",
    "물리학 1분반에서 굴절각을 측정함.",
  ])("거짓 양성 없음: %s", (t) => {
    expect(spellCheck(t)).toEqual([]);
  });

  it("자리 · 설명 · 종류를 돌려준다 (근거 원문은 확인 전이라 비움)", () => {
    const [h] = spellCheck("확인할수 있음.");
    expect(h).toMatchObject({ start: 0, end: 4, from: "확인할수", to: "확인할 수", kind: "띄어쓰기" });
    expect(h.why).toContain("의존 명사");
    expect(h.basis).toBeUndefined();
  });

  it("모두 바꾸기: 뒤에서부터 바꿔 자리가 어긋나지 않는다", () => {
    const t = "확인할수 있음. 왜 안되는지 봄. 제시 함으로써 도움.";
    expect(fix(t)).toBe("확인할 수 있음. 왜 안 되는지 봄. 제시함으로써 도움.");
  });

  it("AI 결과는 본문에 그대로 있고 가명 표지를 건드리지 않는 것만", () => {
    const t = "S012 학생이 실험을 했읍니다. 결과가 좋았음.";
    const r = placeAiFixes(t, [{ from: "했읍니다", to: "했습니다", why: "옛 표기" }, { from: "S012", to: "학생", why: "x" }, { from: "없는 말", to: "말", why: "x" }]);
    expect(r).toHaveLength(1);
    expect(r[0]).toMatchObject({ from: "했읍니다", kind: "맞춤법", rule: "ai" });
  });
});
